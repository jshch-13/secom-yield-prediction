"""Generate a synthetic, code-created wafer die-map dataset for UI/demo purposes.

**This module is fully independent of the SECOM dataset.** SECOM has no
wafer coordinates, lot IDs, equipment IDs, or chamber IDs -- none of that
metadata exists in the real dataset used elsewhere in this project. Every
row produced here is generated by this script from a random seed, exists
only to demonstrate spatial die-map visualization / rule-based pattern
classification / batch PDF reporting engineering, and must never be
presented as a real Fab yield result.

Run as a script to write ``data/processed/synthetic_wafer_map_demo.csv``:

    python simulations/generate_synthetic_wafer_data.py
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT_PATH = PROJECT_ROOT / "data" / "processed" / "synthetic_wafer_map_demo.csv"

DEFECT_PATTERNS: tuple[str, ...] = ("EDGE_RING", "CENTER", "SCRATCH", "RANDOM", "CLEAN")

WAFER_RADIUS_MM: float = 100.0
EDGE_EXCLUSION_MM: float = 3.0
DIE_SIZE_MM: float = 5.0

SCHEMA_COLUMNS: tuple[str, ...] = (
    "lot_id",
    "wafer_id",
    "die_x",
    "die_y",
    "radius",
    "angle_deg",
    "status",
    "defect_pattern",
    "synthetic_data_flag",
)


def _die_grid(wafer_radius_mm: float, die_size_mm: float, edge_exclusion_mm: float) -> pd.DataFrame:
    """Lay out a rectangular die grid and keep only dies inside the circular wafer.

    Args:
        wafer_radius_mm: Wafer radius.
        die_size_mm: Die pitch (square dies assumed).
        edge_exclusion_mm: Ring width near the physical edge with no usable dies.

    Returns:
        DataFrame with ``die_x``, ``die_y``, ``radius``, ``angle_deg`` for
        every die that fits inside ``wafer_radius_mm - edge_exclusion_mm``.
    """
    usable_radius = wafer_radius_mm - edge_exclusion_mm
    coords = np.arange(-wafer_radius_mm, wafer_radius_mm + die_size_mm, die_size_mm)
    xx, yy = np.meshgrid(coords, coords)
    xx, yy = xx.ravel(), yy.ravel()
    radius = np.sqrt(xx**2 + yy**2)
    mask = radius <= usable_radius
    xx, yy, radius = xx[mask], yy[mask], radius[mask]
    angle_deg = np.degrees(np.arctan2(yy, xx))
    return pd.DataFrame({"die_x": xx, "die_y": yy, "radius": radius, "angle_deg": angle_deg})


def _assign_fail_probability(
    dies: pd.DataFrame, pattern: str, wafer_radius_mm: float, rng: np.random.Generator
) -> np.ndarray:
    """Compute a per-die Fail probability for the given synthetic spatial pattern.

    Args:
        dies: Output of :func:`_die_grid`.
        pattern: One of ``DEFECT_PATTERNS``.
        wafer_radius_mm: Wafer radius, used to normalize radial patterns.
        rng: Seeded random generator (also used for the SCRATCH line orientation).

    Returns:
        Array of per-die Fail probabilities in ``[0, 1]``.
    """
    radius_norm = dies["radius"].to_numpy() / wafer_radius_mm

    if pattern == "EDGE_RING":
        return np.clip(0.05 + 0.9 * (radius_norm > 0.75) * (radius_norm - 0.75) / 0.25, 0, 1)
    if pattern == "CENTER":
        return np.clip(0.8 * np.exp(-((radius_norm / 0.25) ** 2)) + 0.03, 0, 1)
    if pattern == "SCRATCH":
        angle = rng.uniform(0, np.pi)
        x, y = dies["die_x"].to_numpy(), dies["die_y"].to_numpy()
        perpendicular_dist = np.abs(-np.sin(angle) * x + np.cos(angle) * y)
        band_width_mm = wafer_radius_mm * 0.06
        return np.clip(0.85 * np.exp(-((perpendicular_dist / band_width_mm) ** 2)) + 0.02, 0, 1)
    if pattern == "RANDOM":
        return np.full(len(dies), 0.12)
    if pattern == "CLEAN":
        return np.full(len(dies), 0.02)
    raise ValueError(f"Unknown defect_pattern: {pattern!r}. Expected one of {DEFECT_PATTERNS}.")


def generate_wafer(
    lot_id: str,
    wafer_id: str,
    pattern: str,
    rng: np.random.Generator,
    wafer_radius_mm: float = WAFER_RADIUS_MM,
    die_size_mm: float = DIE_SIZE_MM,
    edge_exclusion_mm: float = EDGE_EXCLUSION_MM,
) -> pd.DataFrame:
    """Generate one synthetic wafer's die-level PASS/FAIL map for a given spatial pattern.

    Args:
        lot_id: Synthetic lot identifier (arbitrary label, not derived from any real system).
        wafer_id: Synthetic wafer identifier within the lot.
        pattern: One of ``DEFECT_PATTERNS``.
        rng: Seeded NumPy random generator, for reproducibility.
        wafer_radius_mm: Wafer radius used to lay out the circular die mask.
        die_size_mm: Die pitch.
        edge_exclusion_mm: Edge-exclusion ring width with no usable dies.

    Returns:
        DataFrame with columns ``SCHEMA_COLUMNS``, one row per die.
    """
    dies = _die_grid(wafer_radius_mm, die_size_mm, edge_exclusion_mm)
    fail_prob = _assign_fail_probability(dies, pattern, wafer_radius_mm, rng)
    is_fail = rng.random(len(dies)) < fail_prob

    dies["lot_id"] = lot_id
    dies["wafer_id"] = wafer_id
    dies["status"] = np.where(is_fail, "FAIL", "PASS")
    dies["defect_pattern"] = pattern
    dies["synthetic_data_flag"] = True
    return dies[list(SCHEMA_COLUMNS)]


def generate_dataset(
    n_wafers_per_pattern: int = 3, seed: int = 42, patterns: tuple[str, ...] = DEFECT_PATTERNS
) -> pd.DataFrame:
    """Generate a full synthetic wafer-map dataset spanning every defect pattern.

    Args:
        n_wafers_per_pattern: Number of synthetic wafers to generate per pattern.
        seed: Random seed for reproducibility.
        patterns: Defect patterns to include.

    Returns:
        Concatenated DataFrame across all lots/wafers/patterns.
    """
    rng = np.random.default_rng(seed)
    wafers = []
    for pattern in patterns:
        for i in range(n_wafers_per_pattern):
            lot_id = f"SYN-LOT-{pattern[:3]}"
            wafer_id = f"W{i + 1:02d}"
            wafers.append(generate_wafer(lot_id, wafer_id, pattern, rng))
    return pd.concat(wafers, ignore_index=True)


def main() -> None:
    """CLI entry point: generate the synthetic wafer dataset and write it to CSV."""
    parser = argparse.ArgumentParser(
        description=(
            "Generate a synthetic (code-created, not SECOM-derived) wafer die-map "
            "dataset for dashboard/UI demonstration purposes."
        )
    )
    parser.add_argument("--n-wafers-per-pattern", type=int, default=3)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH)
    args = parser.parse_args()

    df = generate_dataset(n_wafers_per_pattern=args.n_wafers_per_pattern, seed=args.seed)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(args.output, index=False)
    print(f"[SYNTHETIC DEMO] wrote {len(df)} die rows across {df['wafer_id'].nunique()} "
          f"wafer IDs x {len(DEFECT_PATTERNS)} patterns to {args.output}")
    print("This dataset is code-generated and is NOT derived from the SECOM dataset "
          "or any real Fab data.")


if __name__ == "__main__":
    main()
