"""Batch-render every synthetic wafer into a multi-page PDF report.

**Synthetic demo only.** This script exists to demonstrate batch reporting
engineering (multi-page PDF generation, consistent per-page disclaimers),
not to report real yield results. Every page -- including the cover page --
carries the disclaimer that the data is code-generated and unrelated to
SECOM or any production Fab.

Run as a script to write ``outputs/simulations/synthetic_wafer_demo_report.pdf``:

    python simulations/batch_wafer_report.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd
from matplotlib.backends.backend_pdf import PdfPages

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from simulations.generate_synthetic_wafer_data import DEFAULT_OUTPUT_PATH, generate_dataset  # noqa: E402
from simulations.wafer_map_visualizer import build_wafer_figure  # noqa: E402

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_REPORT_PATH = PROJECT_ROOT / "outputs" / "simulations" / "synthetic_wafer_demo_report.pdf"

FOOTER_TEXT = (
    "Synthetic wafer-map demonstration. Not derived from the SECOM dataset "
    "or production Fab data."
)


def _build_cover_page(n_wafers: int, patterns: list[str]) -> plt.Figure:
    """Build the report's cover page stating the synthetic-data disclaimer.

    Args:
        n_wafers: Total number of wafers included in the report.
        patterns: Distinct defect patterns represented.

    Returns:
        Matplotlib figure for the cover page.
    """
    fig, ax = plt.subplots(figsize=(8.5, 11))
    ax.axis("off")
    ax.text(0.5, 0.75, "[SYNTHETIC DEMO]", ha="center", fontsize=26, weight="bold")
    ax.text(0.5, 0.68, "Synthetic Wafer-Map Batch Report", ha="center", fontsize=18)
    ax.text(
        0.5,
        0.58,
        FOOTER_TEXT,
        ha="center",
        fontsize=11,
        color="#B00020",
        wrap=True,
    )
    ax.text(
        0.5,
        0.48,
        (
            "All wafer coordinates, lot IDs, and defect patterns in this report were\n"
            "generated by simulations/generate_synthetic_wafer_data.py from a fixed\n"
            "random seed. This report does not represent SECOM sensor analysis results\n"
            "or any real semiconductor manufacturing outcome."
        ),
        ha="center",
        fontsize=10,
        color="#444444",
    )
    ax.text(0.5, 0.35, f"Wafers included: {n_wafers}", ha="center", fontsize=11)
    ax.text(0.5, 0.31, f"Patterns: {', '.join(patterns)}", ha="center", fontsize=11)
    fig.text(0.5, 0.03, FOOTER_TEXT, ha="center", fontsize=8, color="#666666", style="italic")
    return fig


def build_report(df: pd.DataFrame, output_path: Path = DEFAULT_REPORT_PATH) -> Path:
    """Render a multi-page PDF: a cover page plus one page per wafer.

    Args:
        df: Full synthetic wafer dataset (multiple wafers).
        output_path: Destination PDF path.

    Returns:
        The ``output_path`` the PDF was written to.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    wafer_keys = list(df.groupby(["lot_id", "wafer_id"], sort=False).groups.keys())
    patterns = sorted(df["defect_pattern"].unique().tolist())

    with PdfPages(output_path) as pdf:
        cover = _build_cover_page(len(wafer_keys), patterns)
        pdf.savefig(cover)
        plt.close(cover)

        for lot_id, wafer_id in wafer_keys:
            wafer_df = df[(df["lot_id"] == lot_id) & (df["wafer_id"] == wafer_id)]
            fig = build_wafer_figure(wafer_df)
            fig.text(0.5, 0.005, FOOTER_TEXT, ha="center", fontsize=7, color="#666666")
            pdf.savefig(fig)
            plt.close(fig)

    return output_path


if __name__ == "__main__":
    data = (
        pd.read_csv(DEFAULT_OUTPUT_PATH) if DEFAULT_OUTPUT_PATH.exists() else generate_dataset()
    )
    path = build_report(data)
    print(f"[SYNTHETIC DEMO] wrote {path}")
    print(FOOTER_TEXT)
